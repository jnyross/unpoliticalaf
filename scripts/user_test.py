"""Phone user-test pack: render the sheets, check the answer key, score results.

The questions, answers and evidence live in docs/user-test/questions.json.

    python scripts/user_test.py render          # rewrite the generated sheets
    python scripts/user_test.py check           # every answer is still on the built site
    python scripts/user_test.py score FILE.csv  # apply the pass rules to recorded answers
"""
import csv
import html
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PACK = ROOT / "docs" / "user-test"
QUESTIONS = PACK / "questions.json"
SITE = ROOT / "site"
GENERATED = "<!-- Generated by scripts/user_test.py from questions.json. Edit that file, then run `python scripts/user_test.py render`. -->\n\n"


def load():
    return json.loads(QUESTIONS.read_text(encoding="utf-8"))


def page_text(path):
    """Visible text of a built page, with tags removed and spaces collapsed."""
    raw = path.read_text(encoding="utf-8")
    raw = re.sub(r"<(script|style)\b[\s\S]*?</\1>", " ", raw)
    text = html.unescape(re.sub(r"<[^>]+>", " ", raw))
    text = re.sub(r"\s+", " ", text)
    # Tags inside a sentence leave a space before punctuation; close it up.
    text = re.sub(r"\( ", "(", text)
    return re.sub(r" ([,.;:)])", r"\1", text).strip()


def check(site=SITE):
    """Return a list of problems: answers the built site no longer supports."""
    pack = load()
    problems = []
    cache = {}
    for q in pack["questions"]:
        if q["answer"] not in q["options"]:
            problems.append(f"Q{q['id']}: answer {q['answer']} is not one of the options")
        for ev in q["evidence"]:
            path = site / ev["page"]
            if not path.exists():
                problems.append(f"Q{q['id']}: page {ev['page']} is missing from the built site")
                continue
            if path not in cache:
                cache[path] = page_text(path)
            if ev["text"] not in cache[path]:
                problems.append(f"Q{q['id']}: {ev['page']} no longer says: {ev['text']}")
    return problems


def render_questions(pack):
    letters_note = f"Circle one letter for each question. If you don't know, circle E ({pack['not_sure']}). Leave nothing blank."
    out = [GENERATED, f"# {pack['title']}: question sheet\n\n"]
    out.append("Participant code: ______  Start time: ______  Finish time: ______\n\n")
    out.append(
        "Use the Unpolitical website on your phone to answer these questions. "
        f"You have {pack['time_limit_seconds'] // 60} minutes in total. "
        "You can open any page of the site, but please don't use other websites or ask anyone for help. "
        "This is a test of the website, not of you.\n\n"
    )
    out.append(letters_note + "\n")
    for q in pack["questions"]:
        out.append(f"\n## {q['id']}. {q['question']}\n\n")
        for letter, text in q["options"].items():
            out.append(f"- **{letter}** {text}\n")
        out.append(f"- **E** {pack['not_sure']}\n")
    return "".join(out)


def render_key(pack):
    out = [GENERATED, f"# {pack['title']}: answer key\n\n"]
    out.append(
        "For the moderator and marker only. Do not show this to participants. "
        "Questions marked **critical** must all be answered correctly for a person to pass.\n\n"
    )
    out.append("| Q | Topic | Answer | Critical |\n|---|---|---|---|\n")
    for q in pack["questions"]:
        crit = f"Yes: {q['critical_area']}" if q["critical"] else ""
        out.append(f"| {q['id']} | {q['topic']} | **{q['answer']}** | {crit} |\n")
    for q in pack["questions"]:
        out.append(f"\n## {q['id']}. {q['answer']}: {q['options'][q['answer']]}\n\n")
        out.append(q["why"] + "\n\n")
        out.append("Where the site says it:\n\n")
        for ev in q["evidence"]:
            out.append(f"- `{ev['page']}`: \"{ev['text']}\"\n")
    return "".join(out)


def render_marking(pack):
    rules = pack["pass_rules"]
    n = len(pack["questions"])
    crit = [q["id"] for q in pack["questions"] if q["critical"]]
    minutes = pack["time_limit_seconds"] // 60
    out = [GENERATED, f"# {pack['title']}: marking sheet\n\n"]
    out.append(
        f"One copy per participant. Mark each answer against the answer key: 1 for the right letter, 0 for a wrong letter, "
        f"E ({pack['not_sure']}), a blank, or anything written after the {minutes}-minute mark.\n\n"
    )
    out.append("Participant code: ______  Site version (commit): ______  Phone and browser: ______\n\n")
    out.append("Consent note signed or recorded: yes / no  Time taken (mm:ss): ______\n\n")
    out.append("| Q | Critical | Letter given | Right letter | Mark (1 or 0) |\n|---|---|---|---|---|\n")
    for q in pack["questions"]:
        out.append(f"| {q['id']} | {'Yes' if q['critical'] else ''} | | {q['answer']} | |\n")
    out.append(f"\nTotal correct: ____ / {n}\n\n")
    out.append("This person passes only if all of these are true:\n\n")
    out.append(f"- [ ] at least {rules['min_correct_each']} of {n} correct\n")
    out.append(f"- [ ] critical questions {', '.join(map(str, crit))} all correct\n")
    out.append(f"- [ ] finished within {minutes} minutes\n")
    out.append("\n## Group result\n\n")
    out.append("| Participant | Site version | Correct | All critical right | Within time | Passes |\n|---|---|---|---|---|---|\n")
    for i in range(1, rules["participants"] + 1):
        out.append(f"| P{i} | | / {n} | | | |\n")
    out.append(f"| **Total** | | / {n * rules['participants']} | | | |\n\n")
    out.append(
        f"The test is met only if all {rules['participants']} people pass, they all used the same site version, "
        f"and the total is at least {rules['min_correct_total']} of {n * rules['participants']}.\n"
    )
    return "".join(out)


def render_template(pack):
    cols = ["participant", "consent", "eligible", "site_commit", "phone", "seconds_taken"]
    cols += [f"q{q['id']}" for q in pack["questions"]]
    return ",".join(cols) + "\n"


OUTPUTS = {
    "question-sheet.md": render_questions,
    "answer-key.md": render_key,
    "marking-sheet.md": render_marking,
    "results-template.csv": render_template,
}


def rendered():
    pack = load()
    return {name: fn(pack) for name, fn in OUTPUTS.items()}


def score(rows, pack=None):
    """Apply the pass rules to recorded answers. Returns (passed, lines)."""
    pack = pack or load()
    rules = pack["pass_rules"]
    qs = pack["questions"]
    limit = pack["time_limit_seconds"]
    lines, total, ok = [], 0, True
    commits = {r.get("site_commit", "").strip() for r in rows}
    if len(rows) != rules["participants"]:
        ok = False
        lines.append(f"Needs exactly {rules['participants']} participants; found {len(rows)}.")
    if len(commits) != 1 or "" in commits:
        ok = False
        lines.append(f"Everyone must test the same recorded site version; found {sorted(commits)}.")
    for r in rows:
        who = r.get("participant", "?")
        correct = sum(1 for q in qs if r.get(f"q{q['id']}", "").strip().upper() == q["answer"])
        missed_crit = [q["id"] for q in qs if q["critical"] and r.get(f"q{q['id']}", "").strip().upper() != q["answer"]]
        try:
            secs = float(r.get("seconds_taken", ""))
        except ValueError:
            secs = None
        reasons = []
        if r.get("consent", "").strip().lower() != "yes":
            reasons.append("no recorded consent")
        if r.get("eligible", "").strip().lower() != "yes":
            reasons.append("not recorded as eligible")
        if correct < rules["min_correct_each"]:
            reasons.append(f"{correct} correct, needs {rules['min_correct_each']}")
        if missed_crit:
            reasons.append("missed critical " + ", ".join(f"Q{i}" for i in missed_crit))
        if secs is None or secs > limit:
            reasons.append(f"time {r.get('seconds_taken') or 'not recorded'}s, limit {limit}s")
        total += correct
        if reasons:
            ok = False
            lines.append(f"{who}: {correct}/{len(qs)}, does not pass ({'; '.join(reasons)})")
        else:
            lines.append(f"{who}: {correct}/{len(qs)}, passes")
    need = rules["min_correct_total"]
    if total < need:
        ok = False
    lines.append(f"Total: {total}/{len(qs) * len(rows)} (needs {need})")
    lines.append("Result: MET" if ok else "Result: NOT MET")
    return ok, lines


def main(argv):
    cmd = argv[1] if len(argv) > 1 else ""
    if cmd == "render":
        for name, text in rendered().items():
            (PACK / name).write_text(text, encoding="utf-8")
            print(f"wrote docs/user-test/{name}")
        return 0
    if cmd == "check":
        problems = check()
        for p in problems:
            print(p)
        print("Answer key matches the built site." if not problems else f"{len(problems)} problem(s).")
        return 1 if problems else 0
    if cmd == "score" and len(argv) == 3:
        with open(argv[2], newline="", encoding="utf-8") as f:
            ok, lines = score(list(csv.DictReader(f)))
        print("\n".join(lines))
        return 0 if ok else 1
    print(__doc__)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv))
